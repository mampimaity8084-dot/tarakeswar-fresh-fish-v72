-- Create/update customer + order atomically from the public customer app.
create or replace function public.create_order_with_customer(
 p_name text, p_mobile text, p_area text, p_referral_code text, p_total numeric, p_items jsonb
) returns table(order_id uuid, order_no text, customer_referral_code text)
language plpgsql security definer set search_path=public as $$
declare
 v_mobile text := regexp_replace(coalesce(p_mobile,''),'[^0-9]','','g');
 v_customer public.customers%rowtype;
 v_referrer uuid;
 v_order public.orders%rowtype;
 v_item jsonb;
 v_ref text;
begin
 if length(v_mobile)=12 and left(v_mobile,2)='91' then v_mobile:=right(v_mobile,10); end if;
 if length(v_mobile) <> 10 then raise exception 'Invalid mobile number'; end if;
 if trim(coalesce(p_name,''))='' or trim(coalesce(p_area,''))='' then raise exception 'Name and area required'; end if;

 select * into v_customer from public.customers where mobile=v_mobile;
 if not found then
   v_ref := 'TFF' || upper(substr(md5(v_mobile || clock_timestamp()::text),1,6));
   if p_referral_code is not null and trim(p_referral_code)<>'' then
      select id into v_referrer from public.customers where upper(referral_code)=upper(trim(p_referral_code)) limit 1;
   end if;
   insert into public.customers(name,mobile,area,referral_code,referred_by)
   values(trim(p_name),v_mobile,trim(p_area),v_ref,v_referrer) returning * into v_customer;
 else
   update public.customers set name=trim(p_name),area=trim(p_area),updated_at=now() where id=v_customer.id returning * into v_customer;
 end if;

 insert into public.orders(customer_id,total) values(v_customer.id,greatest(coalesce(p_total,0),0)) returning * into v_order;
 for v_item in select * from jsonb_array_elements(coalesce(p_items,'[]'::jsonb)) loop
   insert into public.order_items(order_id,product_id,product_name,qty,unit,unit_price,line_total)
   values(v_order.id,v_item->>'product_id',coalesce(v_item->>'name','Product'),coalesce((v_item->>'qty')::numeric,1),v_item->>'unit',coalesce((v_item->>'unit_price')::numeric,0),coalesce((v_item->>'line_total')::numeric,0));
 end loop;
 return query select v_order.id,v_order.order_no,v_customer.referral_code;
end $$;

grant execute on function public.create_order_with_customer(text,text,text,text,numeric,jsonb) to anon, authenticated;

-- Automatic Fresh Points + referral milestone + monthly VIP when an order becomes Delivered.
create or replace function public.apply_delivered_rewards() returns trigger
language plpgsql security definer set search_path=public as $$
declare
 v_points int;
 v_month_orders int;
 v_cust public.customers%rowtype;
 v_success_refs int;
 v_target numeric(10,2):=0;
 v_delta numeric(10,2):=0;
begin
 if new.status='Delivered' and old.status is distinct from 'Delivered' then
   v_points := floor(greatest(new.total,0)/500)::int;
   update public.orders set points_awarded=v_points, delivered_at=coalesce(new.delivered_at,now()) where id=new.id;
   update public.customers set fresh_points=fresh_points+v_points,total_orders=total_orders+1,lifetime_spend=lifetime_spend+new.total,updated_at=now() where id=new.customer_id returning * into v_cust;
   if v_points>0 then insert into public.reward_ledger(customer_id,order_id,kind,points,note) values(new.customer_id,new.id,'fresh_points',v_points,'₹500 per Fresh Point'); end if;

   select count(*) into v_month_orders from public.orders where customer_id=new.customer_id and status='Delivered' and coalesce(delivered_at,created_at)>=date_trunc('month',now());
   if v_month_orders>=4 then update public.customers set vip_member=true where id=new.customer_id; end if;

   if v_cust.referred_by is not null and v_cust.referral_rewarded=false then
     update public.customers set referral_rewarded=true where id=new.customer_id;
     select count(*) into v_success_refs from public.customers where referred_by=v_cust.referred_by and referral_rewarded=true;
     v_target := case when v_success_refs>=10 then 400 when v_success_refs>=5 then 200 when v_success_refs>=3 then 100 when v_success_refs>=1 then 30 else 0 end;
     select greatest(v_target-referral_credit_total,0) into v_delta from public.customers where id=v_cust.referred_by;
     if v_delta>0 then
       update public.customers set wallet_credit=wallet_credit+v_delta,referral_credit_total=v_target,vip_member=(vip_member or v_success_refs>=10),updated_at=now() where id=v_cust.referred_by;
       insert into public.reward_ledger(customer_id,order_id,kind,credit,note) values(v_cust.referred_by,new.id,'referral',v_delta,'Successful referral milestone: '||v_success_refs);
     end if;
   end if;
 end if;
 return new;
end $$;

drop trigger if exists trg_apply_delivered_rewards on public.orders;
create trigger trg_apply_delivered_rewards after update of status on public.orders for each row execute function public.apply_delivered_rewards();

