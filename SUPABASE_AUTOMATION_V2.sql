create extension if not exists pgcrypto;

create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  mobile text not null unique,
  area text,
  referral_code text unique,
  referred_by uuid references public.customers(id),
  referral_rewarded boolean not null default false,
  fresh_points integer not null default 0,
  wallet_credit numeric(10,2) not null default 0,
  referral_credit_total numeric(10,2) not null default 0,
  total_orders integer not null default 0,
  lifetime_spend numeric(12,2) not null default 0,
  vip_member boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_no text not null unique default ('TFF-' || to_char(now(),'YYMMDD') || '-' || upper(substr(gen_random_uuid()::text,1,6))),
  customer_id uuid not null references public.customers(id) on delete restrict,
  total numeric(12,2) not null default 0,
  status text not null default 'New' check (status in ('New','Confirmed','Delivered','Cancelled')),
  created_at timestamptz not null default now(),
  delivered_at timestamptz,
  points_awarded integer not null default 0,
  feedback_sent_at timestamptz,
  feedback_status text,
  feedback_error text
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id text,
  product_name text not null,
  qty numeric(10,2) not null default 1,
  unit text,
  unit_price numeric(12,2) not null default 0,
  line_total numeric(12,2) not null default 0
);

create table if not exists public.reward_ledger (
  id bigint generated by default as identity primary key,
  customer_id uuid not null references public.customers(id) on delete cascade,
  order_id uuid references public.orders(id) on delete set null,
  kind text not null,
  points integer not null default 0,
  credit numeric(10,2) not null default 0,
  note text,
  created_at timestamptz not null default now()
);

create table if not exists public.offers (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text,
  badge text default '🔥',
  price numeric(12,2),
  start_at timestamptz not null,
  end_at timestamptz not null,
  priority integer not null default 10,
  enabled boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.public_settings (
  id integer primary key default 1 check (id=1),
  feedback_form_url text,
  whatsapp_number text default '918100227692',
  updated_at timestamptz not null default now()
);
